/* --- line number accuracy --- */

static void test_line_numbers(void)
{
   slop_finding_t f[MAX_F];
   const char *src = "int a = 1;\n"
                     "// TODO:\n" /* line 2 */
                     "int b = 2;\n"
                     "// string\n" /* line 4 */
                     "int c = 3;\n";
   int n = slop_detect_buf(src, 0, f, MAX_F);
   assert(n >= 2);
   assert(has_finding_on_line(f, n, 2));
   assert(has_finding_on_line(f, n, 4));
   printf("  test_line_numbers: ok\n");
}

/* --- category label --- */

